"""MSS Configurator の XML から .cfg を逆生成する。

pfsoc_mss.exe のバッチ生成（.cfg -> XML）を何度も実行し、目的の XML と
一致する .cfg を探す。結果の .cfg は MSS Configurator で開いて画面で確認できる。
"""
