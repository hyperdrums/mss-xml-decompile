CACHE = os.path.join(HERE, "cache")
WORKERS = int(os.environ.get("MSSDC_WORKERS", "14"))

# ---------------------------------------------------------------- XML


def flatten(path):
    """XML を {キー: 値} にする。生成日時など設定に関係しない項目は除く。"""
    root = ET.parse(path).getroot()
    out = {}
    di = root.find("design_information")
    if di is not None:
        for t in ("mpfs_part_no", "mpfs_package"):
            e = di.find(t)
            if e is not None:
                out["design/" + t] = (e.text or "").strip()
    for sec in root:
        if sec.tag == "design_information":
            continue
        for sub in sec:
            mems = sub.find("mem_elements")
            if mems is not None:
                for m in mems:
                    out[f"{sec.tag}/{sub.tag}/{m.get('name')}"] = f"{(m.text or '').strip()}@{m.get('size')}"
            regs = sub.find("registers")
            if regs is None:
                continue
            for r in regs:
                for f in r:
                    out[f"{sec.tag}/{sub.tag}/{r.get('name')}.{f.get('name')}"] = (f.text or "").strip()
    return out


def diff_keys(a, b):
    return sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))

# ---------------------------------------------------------------- cfg


def read_cfg(path):
    params = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            s = line.rstrip("\r\n")
            if not s.strip() or s.lstrip().startswith("#"):
                continue
            m = re.match(r"(\S+)\s*(.*)$", s)
            params[m.group(1)] = m.group(2).strip()
    return params


def cfg_text(params):
    lines = ["# Generated by mssdc.py"]
    lines += [f"{k:<52}{v}" for k, v in sorted(params.items())]
    return "\n".join(lines) + "\n"


def write_cfg(params, path):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(cfg_text(params))

# ---------------------------------------------------------------- catalog


def load_catalog():
    types = {}
    with open(os.path.join(DATA, "params.txt"), encoding="utf-8", errors="replace") as f:
        for line in f:
            p = line.split()
            if p:
                types[p[0]] = p[1] if len(p) > 1 else "string"
    choices = {}
    with open(os.path.join(DATA, "choices.txt"), encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"(\S+)\s+(\S+)\s+\"(.*)\"", line.strip())
            if m:
                choices.setdefault(m.group(1), []).append((m.group(2), m.group(3)))
    return types, choices


TYPES, CHOICES = load_catalog()


def candidates(name, cur):
    """列挙できるパラメータの候補値。数値・文字列は None。"""
    t = TYPES.get(name, "string")
    if t == "bool":
        return ["true", "false"]
    if t in CHOICES:
        return [v for v, _ in CHOICES[t]]
    return None


def label(name, value):
    t = TYPES.get(name)
    for v, lab in CHOICES.get(t, []):
        if v == value:
            return lab
    return None

# ---------------------------------------------------------------- generation


class Gen:
    """cfg -> (実際に使われた cfg, XML の平坦化) を、キャッシュ付きで求める。"""

    def __init__(self):
        os.makedirs(CACHE, exist_ok=True)
        self.calls = 0

    def key(self, params):
        return hashlib.sha1(cfg_text(params).encode()).hexdigest()

    def run(self, params):
        k = self.key(params)
        cp = os.path.join(CACHE, k + ".json")
        if os.path.exists(cp):
            try:
                with open(cp, encoding="utf-8") as f:
                    d = json.load(f)
                return d["cfg"], d["xml"], d["ok"]
            except (ValueError, KeyError):
                os.remove(cp)  # 書き込み途中で壊れたものは作り直す
        self.calls += 1
        tmp = tempfile.mkdtemp(prefix="mssdc_", dir=CACHE)
        try:
            write_cfg(params, os.path.join(tmp, "in.cfg"))
            os.makedirs(os.path.join(tmp, "out"))
            r = subprocess.run([EXE, "-GENERATE", "-CONFIGURATION_FILE:in.cfg", "-OUTPUT_DIR:out",
                                "-LOGFILE:gen.log"], cwd=tmp, capture_output=True, text=True,
                               errors="replace", timeout=300)
            xs = [x for x in os.listdir(os.path.join(tmp, "out")) if x.endswith("_mss_cfg.xml")]
            cs = [x for x in os.listdir(os.path.join(tmp, "out")) if x.endswith(".cfg")]
            ok = r.returncode == 0 and xs and cs
            if ok:
                eff = read_cfg(os.path.join(tmp, "out", cs[0]))
                xml = flatten(os.path.join(tmp, "out", xs[0]))
            else:
                eff, xml = params, {}
            d = {"cfg": eff, "xml": xml, "ok": bool(ok), "log": r.stdout[-4000:]}
            with open(cp + ".tmp", "w", encoding="utf-8") as f:
                json.dump(d, f)
            os.replace(cp + ".tmp", cp)
            return eff, xml, bool(ok)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def log(self, params):
        cp = os.path.join(CACHE, self.key(params) + ".json")
        if not os.path.exists(cp):
            return ""
        with open(cp, encoding="utf-8") as f:
            return json.load(f).get("log", "")

    def many(self, list_of_params):
        with cf.ThreadPoolExecutor(WORKERS) as ex:
            return list(ex.map(self.run, list_of_params))

# ---------------------------------------------------------------- search


def score(xml, target):
    if not xml:
        return 10 ** 9
    return len(diff_keys(xml, target))


# 値を変えても、別の設定を有効にしないと反映されないパラメータ
GATES = [
    (r"^DDR_.*_PHY_OFFSET$", {"MSS_MANUAL_DDR_PHY_OFFSET_ENABLE": "true"}),
]


def gate_for(name):
    for pat, extra in GATES:
        if re.search(pat, name):
            return extra
    return {}


# DRC のエラー文とパラメータの対応（エラー文にパラメータ名が出ないもの）
DRC_HINTS = [
    (r"muxing", ["EMMC_SD_SWITCHING"]),
    (r"SD_VOLT", ["SD_VOLT_PORTS"]),
    (r"support only [0-9.]+ volts in", ["SD_SDIO_SPEED_MODE", "EMMC_SPEED_MODE"]),
]


def conflicts(log, params, exclude):
    """DRC のエラー文から、ぶつかっている相手のパラメータを探す。"""
    out = []
    for line in log.splitlines():
        if "ERROR" not in line:
            continue
        for pat, names in DRC_HINTS:
            if re.search(pat, line):
                out += [n for n in names if n in params and n != exclude and n not in out]
        for tok in re.findall(r"[A-Z][A-Z0-9_]{2,}", line):
            t = tok
            while t and t not in params:  # MMUART_0_RXD -> MMUART_0
                t = t.rsplit("_", 1)[0] if "_" in t else ""
            if t and t != exclude and t not in out and t.count("_") >= tok.count("_") - 1                     and not exclude.startswith(t + "_"):
                out.append(t)
    return out


def repairs(n, v, cur, gen):
    """1 つ変えて DRC エラーになったとき、相手も変えた組合せを作る。"""
    trial = dict(cur, **{n: v})
    out = []
    cs = conflicts(gen.log(trial), cur, n)[:4]
    for c in cs:
        for cv in (candidates(c, cur[c]) or []):
            if cv != cur[c]:
                out.append({n: v, c: cv})
    if len(cs) > 1:  # 相手が複数なら、まとめて空ける
        both = {n: v}
        for c in cs:
            cand = candidates(c, cur[c]) or []
            free = next((x for x in ("UNUSED", "FABRIC", "DISABLED", "false") if x in cand), None)
            if free:
                both[c] = free
        if len(both) > 2:
            out.append(both)
    return out


def parse_num(v):
    try:
        if v.lower().startswith("0x"):
            return float(int(v.replace("_", ""), 16)), "hex"
        return float(v), ("float" if "." in v else "int")
    except ValueError:
        return None, None


def fmt_num(v, kind, like):
    if kind == "hex":
        h = f"{int(round(v)) & 0xFFFFFFFF:08X}"
        return f"0x{h[:4]}_{h[4:]}"
    if kind == "float":
        nd = len(like.split(".")[1])
        return f"{v:.{nd}f}"
    return str(int(round(v)))


def num_probes(name, value):
    """数値パラメータの感度を見るための、別の値の候補（範囲外で失敗することがあるので複数）。"""
    v0, kind = parse_num(value)
    if v0 is None:
        return []
    if kind == "hex":
        vs = [v0 + 0x1000_0000, v0 - 0x1000_0000]
    elif v0 == 0:
        vs = [1.0, 2.0]
    else:
        vs = [v0 * 1.25, v0 * 0.8, v0 + 1, v0 - 1]
    out = []
    for v in vs:
        f = fmt_num(v, kind, value)
        if v >= 0 and f != value and f not in out:
            out.append(f)
    return out


def num_probe(name, value):
    p = num_probes(name, value)
    return p[0] if p else None


def linear_guesses(name, cur, x0, x1, v1s, target):
    v0, kind = parse_num(cur[name])
    v1, _ = parse_num(v1s)
    out = set()
    for k in diff_keys(x0, x1):
        if k not in target or x0.get(k) == target[k]:
            continue
        try:
            f0, f1, ft = int(x0[k], 0), int(x1[k], 0), int(target[k], 0)
        except (KeyError, ValueError, TypeError):
            continue
        if f1 != f0:
            g = v0 + (ft - f0) * (v1 - v0) / (f1 - f0)
            if g >= 0:
                out.add(fmt_num(g, kind, cur[name]))
    return sorted(out)[:6]


def decompile(target, base, scope_re=None, max_pass=8, log=print):
    gen = Gen()
    cur, xml, ok = gen.run(base)
    if not ok:
        raise SystemExit("ベースの cfg で生成できなかった")
    best = score(xml, target)
    log(f"start: 不一致 {best}")
    names = sorted(cur)
    if scope_re:
        names = [n for n in names if re.search(scope_re, n)]
    sens = {}  # パラメータ -> 動いた XML の項目

    def relevant(n, mism):
        return n not in sens or bool(sens[n] & mism)

    def accept(moves, npass):
        nonlocal cur, xml, best
        changed = False
        for s, upd in sorted(moves, key=lambda t: t[0]):
            eff, x, okp = gen.run(dict(cur, **upd))
            s2 = score(x, target)
            if okp and s2 < best:
                cur, xml, best = eff, x, s2
                changed = True
                log(f"  pass{npass}: {upd}  -> 不一致 {best}")
        return changed

    for npass in range(1, max_pass + 1):
        improved = False
        mism = set(diff_keys(xml, target))
        if not mism:
            break
        # 列挙できるパラメータ：全候補を試す
        probes, owners = [], []
        for n in names:
            c = candidates(n, cur.get(n, ""))
            if c and relevant(n, mism):
                for v in c:
                    if v != cur.get(n):
                        probes.append(dict(cur, **{n: v}))
                        owners.append((n, {n: v}))
        moves = {}
        res = gen.many(probes)
        failed = [(n, upd) for (n, upd), r in zip(owners, res) if not r[2]]
        rep = []
        for n, upd in failed:
            rep += repairs(n, upd[n], cur, gen)
        owners = owners + [(list(u)[0], u) for u in rep]
        res = res + gen.many([dict(cur, **u) for u in rep])
        for (n, upd), (eff, x, okp) in zip(owners, res):
            if not okp:
                continue
            sens.setdefault(n, set()).update(diff_keys(x, xml))
            s = score(x, target)
            if s < best and (n not in moves or s < moves[n][0]):
                moves[n] = (s, upd)
        improved |= accept(moves.values(), npass)
        # 数値パラメータ：2 点から線形に推定
        mism = set(diff_keys(xml, target))
        nums = [n for n in names if n in cur and candidates(n, cur[n]) is None
                and num_probe(n, cur[n]) is not None and relevant(n, mism)]
        jobs = []
        for n in nums:
            g = gate_for(n)
            b0 = dict(cur, **g)
            for pv in num_probes(n, cur[n]):
                jobs.append((n, g, b0, dict(b0, **{n: pv})))
        flat = [j[2] for j in jobs] + [j[3] for j in jobs]
        res = gen.many(flat)
        r0, r1 = res[:len(jobs)], res[len(jobs):]
        guess_trials, gowners = [], []
        for (n, g, b0, b1), (e0, x0, ok0), (e1, x1, ok1) in zip(jobs, r0, r1):
            if not (ok0 and ok1):
                continue
            sens.setdefault(n, set()).update(diff_keys(x0, x1))
            for gv in linear_guesses(n, dict(cur, **{n: e0.get(n, cur[n])}), x0, x1, b1[n], target):
                upd = dict(g, **{n: gv})
                if upd in [u for _, u in gowners]:
                    continue
                guess_trials.append(dict(cur, **upd))
                gowners.append((n, upd))
        moves = {}
        for (n, upd), (eff, x, okp) in zip(gowners, gen.many(guess_trials)):
            s = score(x, target)
            if okp and s < best and (n not in moves or s < moves[n][0]):
                moves[n] = (s, upd)
        improved |= accept(moves.values(), npass)
        log(f"pass{npass} 終了: 不一致 {best}（生成 {gen.calls} 回）")
        if not improved:
            break
    log(f"end: 不一致 {best}（生成 {gen.calls} 回）")
    return cur, xml

# ---------------------------------------------------------------- CLI


def base_for(target):
    """目的の XML に合わせたベースの cfg（Icicle の preset にデバイス・パッケージを合わせる）。"""
    p = read_cfg(os.path.join(DATA, "PFSOC_MSS_PRESETS", "Icicle_Linux.cfg"))
    if target.get("design/mpfs_part_no"):
        p["DIE"] = target["design/mpfs_part_no"]
    if target.get("design/mpfs_package"):
        p["PACKAGE"] = target["design/mpfs_package"]
    return p


def cmd_decompile(a):
    target = flatten(a.xml)
    base = read_cfg(a.base) if a.base else base_for(target)
    cfg, xml = decompile(target, base, a.scope)
    write_cfg(cfg, a.out)
    rest = diff_keys(xml, target)
    with open(a.out + ".residual.txt", "w", encoding="utf-8") as f:
        for k in rest:
            f.write(f"{k}\tgen={xml.get(k)}\ttarget={target.get(k)}\n")
    print(f"cfg: {a.out}\n残りの不一致: {len(rest)} 項目（{a.out}.residual.txt）")


def cmd_flatdiff(a):
    x, y = flatten(a.a), flatten(a.b)
    for k in diff_keys(x, y):
        print(f"{k}\t{x.get(k)}\t{y.get(k)}")


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    d = sp.add_parser("decompile")
    d.add_argument("xml")
    d.add_argument("-o", "--out", required=True)
    d.add_argument("--base")
    d.add_argument("--scope", help="対象のパラメータ名の正規表現")
    d.set_defaults(func=cmd_decompile)
    f = sp.add_parser("flatdiff")
    f.add_argument("a")
    f.add_argument("b")
    f.set_defaults(func=cmd_flatdiff)
    a = ap.parse_args()
    a.func(a)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
